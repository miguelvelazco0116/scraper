ROOT = Path(__file__).resolve().parents[2]
DIAGNOSTICS = ROOT / "diagnostics" / "heb"
BASE_URL = "https://www.heb.com.mx/"


class HEBBlocked(RuntimeError):
    pass


class HEBNetworkUnavailable(RuntimeError):
    pass


class HEBScraper:
    """HEB México category scraper using storefront VTEX productSearchV3.

    The browser is the source of truth: the scraper listens to the structured
    productSearchV3 responses generated by HEB's own storefront while the
    category is opened and the native "show more" control is used.
    """

    BLOCK_MARKERS = (
        "access denied",
        "request rejected",
        "captcha",
        "verifica que eres humano",
        "verify you are human",
        "forbidden",
    )

    SHOW_MORE_SELECTORS = (
        ".vtex-search-result-3-x-buttonShowMore button",
        ".vtex-search-result-3-x-buttonShowMore",
        'button:has-text("Mostrar más")',
        'button:has-text("Mostrar mas")',
        'button:has-text("Ver más")',
        'button:has-text("Ver mas")',
        'text="Mostrar más"',
        'text="Mostrar mas"',
        'text="Ver más"',
        'text="Ver mas"',
    )

    def __init__(
        self,
        *,
        headless: bool = False,
        browser_channel: str | None = "chrome",
        wait_ms: int = 1_100,
        max_show_more_clicks: int = 80,
    ) -> None:
        self.headless = headless
        self.browser_channel = browser_channel
        self.wait_ms = wait_ms
        self.max_show_more_clicks = max_show_more_clicks
        self.run_meta: dict = {}
        self._payloads: list[dict] = []
        self._response_errors: list[str] = []
        self._response_urls: list[str] = []

    @staticmethod
    def _body_text(page) -> str:
        try:
            return page.locator("body").inner_text(timeout=8_000)
        except Exception:
            return ""

    def _save_diagnostics(self, page, prefix: str) -> None:
        DIAGNOSTICS.mkdir(parents=True, exist_ok=True)
        safe = re.sub(r"[^a-zA-Z0-9_-]+", "_", prefix)

        try:
            page.screenshot(
                path=str(DIAGNOSTICS / f"heb_{safe}.png"),
                full_page=True,
            )
        except Exception:
            pass

        try:
            (DIAGNOSTICS / f"heb_{safe}.html").write_text(
                page.content(),
                encoding="utf-8",
            )
        except Exception:
            pass

        payload = dict(self.run_meta)
        payload["response_errors"] = self._response_errors[-50:]
        payload["response_urls"] = self._response_urls[-100:]
        try:
            (DIAGNOSTICS / f"heb_{safe}.json").write_text(
                json.dumps(
                    payload,
                    ensure_ascii=False,
                    indent=2,
                    default=str,
                ),
                encoding="utf-8",
            )
        except Exception:
            pass

    def _assert_not_blocked(
        self,
        page,
        status: int | None = None,
    ) -> None:
        body = self._body_text(page).casefold()
        blocked = (
            status in (401, 403, 429)
            or "/blocked" in (page.url or "").casefold()
            or any(marker in body for marker in self.BLOCK_MARKERS)
        )
        if not blocked:
            return

        self.run_meta["blocked_detected"] = True
        self.run_meta["blocked_status"] = status
        self.run_meta["blocked_url"] = page.url
        self._save_diagnostics(page, "blocked")
        raise HEBBlocked(
            "HEB bloqueó o desafió la sesión automatizada. "
            "Se guardaron diagnósticos."
        )

    def _capture_product_search_response(self, response) -> None:
        url = response.url
        if "operationName=productSearchV3" not in url:
            return

        self._response_urls.append(url)
        try:
            payload = response.json()
        except Exception as exc:
            self._response_errors.append(
                f"{type(exc).__name__}: {exc}"
            )
            return

        if not isinstance(payload, dict):
            return

        search = (payload.get("data") or {}).get("productSearch")
        if not isinstance(search, dict):
            return

        self._payloads.append(payload)

    @staticmethod
    def _offer_candidates(product: dict) -> list[dict]:
        candidates: list[dict] = []
        for item in product.get("items") or []:
            if not isinstance(item, dict):
                continue
            item_id = clean_text(str(item.get("itemId") or ""))
            ean = clean_text(str(item.get("ean") or ""))
            for seller in item.get("sellers") or []:
                if not isinstance(seller, dict):
                    continue
                offer = seller.get("commertialOffer") or {}
                if not isinstance(offer, dict):
                    continue
                candidates.append(
                    {
                        "item_id": item_id,
                        "ean": ean,
                        "seller_default": bool(
                            seller.get("sellerDefault")
                        ),
                        "price": offer.get("Price"),
                        "regular": offer.get("ListPrice"),
                        "available": offer.get("AvailableQuantity"),
                        "discount_highlights": offer.get(
                            "discountHighlights"
                        )
                        or [],
                        "teasers": offer.get("teasers") or [],
                    }
                )
        return candidates

    @classmethod
    def _best_offer(cls, product: dict) -> dict:
        candidates = cls._offer_candidates(product)
        if not candidates:
            return {
                "item_id": None,
                "ean": None,
                "price": None,
                "regular": None,
                "available": None,
                "promotions": [],
            }

        def priority(value: dict) -> tuple[int, int, float]:
            available = value.get("available")
            in_stock = (
                available is not None and int(available) > 0
            )
            price = value.get("price")
            numeric_price = (
                float(price)
                if price is not None
                else float("inf")
            )
            return (
                0 if value.get("seller_default") else 1,
                0 if in_stock else 1,
                numeric_price,
            )

        candidates.sort(key=priority)
        chosen = candidates[0]

        promo_names: list[str] = []
        for value in (
            chosen.get("discount_highlights") or []
        ) + (chosen.get("teasers") or []):
            if isinstance(value, dict) and value.get("name"):
                promo_names.append(str(value["name"]))

        price = chosen.get("price")
        regular = chosen.get("regular")
        available = chosen.get("available")

        current = float(price) if price is not None else None
        list_price = (
            float(regular) if regular is not None else None
        )
        quantity = (
            int(available) if available is not None else None
        )

        if current is not None:
            if list_price is None or list_price <= 0:
                list_price = current
            if current > list_price:
                current, list_price = list_price, current

        return {
            "item_id": chosen.get("item_id"),
            "ean": chosen.get("ean"),
            "price": current,
            "regular": list_price,
            "available": quantity,
            "promotions": list(dict.fromkeys(promo_names)),
        }

    @classmethod
    def _row_from_product(
        cls,
        product: dict,
        category: Category,
        location: Location,
    ) -> dict | None:
        name = clean_text(product.get("productName"))
        product_url = clean_text(product.get("link"))
        if not name or not product_url:
            return None

        offer = cls._best_offer(product)
        item_id = clean_text(offer.get("item_id"))
        product_reference = clean_text(
            str(product.get("productReference") or "")
        )
        product_id = clean_text(
            str(product.get("productId") or "")
        )
        sku = item_id or product_reference or product_id
        if not sku:
            return None

        current = offer.get("price")
        regular = offer.get("regular")
        available = offer.get("available")

        if available is None:
            availability_status = UNKNOWN
            is_available = None
            availability_raw = (
                "productSearchV3 AvailableQuantity=None"
            )
        elif int(available) > 0:
            availability_status = AVAILABLE
            is_available = 1
            availability_raw = (
                f"productSearchV3 AvailableQuantity={available}"
            )
        else:
            availability_status = UNAVAILABLE
            is_available = 0
            availability_raw = (
                f"productSearchV3 AvailableQuantity={available}"
            )

        promotions = offer.get("promotions") or []
        if (
            current is not None
            and regular is not None
            and current < regular
            and not promotions
        ):
            promotions = ["Precio promocional"]

        return {
            "scrape_timestamp": datetime.now()
            .astimezone()
            .isoformat(timespec="seconds"),
            "retailer": "HEB",
            "city": location.city,
            "state": location.state,
            "postal_code": location.postal_code,
            "store": location.store,
            "store_id": location.store_id,
            "department": category.department,
            "category": category.name,
            "subcategory": category.subcategory,
            "sub_subcategory": category.sub_subcategory,
            "category_id": category.id,
            "sku": sku,
            "brand": clean_text(product.get("brand")),
            "product": name,
            "price_current": current,
            "price_regular": regular,
            "promotion": clean_text(
                " | ".join(promotions)
            ),
            "availability_status": availability_status,
            "is_available": is_available,
            "availability_raw": availability_raw,
            "pickup_available": (
                None
                if is_available is None
                else bool(is_available)
            ),
            "store_context_verified": False,
            "store_context_method": (
                "heb_vtex_productSearchV3_session_context"
            ),
            "url": urljoin(BASE_URL, product_url),
            "price_raw": (
                "productSearchV3 "
                f"Price={current} "
                f"ListPrice={regular} "
                f"AvailableQuantity={available}"
            ),
        }

    @staticmethod
    def _payload_products(payload: dict) -> tuple[list[dict], int | None]:
        search = (payload.get("data") or {}).get("productSearch") or {}
        products = search.get("products") or []
        target = search.get("recordsFiltered")
        try:
            parsed_target = int(target) if target is not None else None
        except (TypeError, ValueError):
            parsed_target = None
        return [
            value for value in products
            if isinstance(value, dict)
        ], parsed_target

    @classmethod
    def _rows_from_payloads(
        cls,
        payloads: list[dict],
        category: Category,
        location: Location,
    ) -> tuple[list[dict], int | None]:
        rows_by_key: dict[str, dict] = {}
        target: int | None = None

        for payload in payloads:
            products, payload_target = cls._payload_products(payload)
            if payload_target is not None:
                target = max(target or 0, payload_target)

            for product in products:
                row = cls._row_from_product(
                    product,
                    category,
                    location,
                )
                if row is None:
                    continue
                key = (
                    clean_text(row.get("sku"))
                    or clean_text(row.get("url"))
                )
                if key:
                    rows_by_key[key] = row

        return list(rows_by_key.values()), target

    @staticmethod
    def _page_url(base_url: str, page_number: int) -> str:
        parts = urlsplit(base_url)
        query = dict(parse_qsl(parts.query, keep_blank_values=True))
        if page_number <= 1:
            query.pop("page", None)
        else:
            query["page"] = str(page_number)
        return urlunsplit(
            (
                parts.scheme,
                parts.netloc,
                parts.path,
                urlencode(query),
                parts.fragment,
            )
        )

    @staticmethod
    def _target_from_body(page) -> int | None:
        try:
            body = page.locator("body").inner_text(timeout=8_000)
        except Exception:
            return None
        match = re.search(
            r"([0-9][0-9.,]*)\s+resultados\b",
            body,
            flags=re.I,
        )
        if not match:
            return None
        digits = re.sub(r"[^0-9]", "", match.group(1))
        return int(digits) if digits else None

    @staticmethod
    def _dom_product_cards(page) -> list[dict]:
        return page.locator("body").evaluate(
            r"""
            () => {
              const norm = value =>
                String(value || '').replace(/\s+/g, ' ').trim();
              const out = [];
              const seen = new Set();

              for (const a of Array.from(document.querySelectorAll('a[href]'))) {
                let url;
                try { url = new URL(a.href, location.href); } catch (_) { continue; }
                if (url.origin !== location.origin) continue;

                const pathname = url.pathname.replace(/\/+$/, '');
                if (!/\/p$/i.test(pathname)) continue;

                const key = url.origin + pathname;
                if (seen.has(key)) continue;

                let card = a;
                let cardText = '';
                for (let i = 0; i < 12 && card; i++, card = card.parentElement) {
                  const text = norm(card.innerText || card.textContent);
                  if (
                    text.length >= 4 &&
                    text.length <= 2200 &&
                    /\$\s*[0-9]/.test(text)
                  ) {
                    cardText = text;
                    break;
                  }
                }

                const image = a.querySelector('img[alt]');
                const title =
                  norm(a.getAttribute('aria-label')) ||
                  norm(a.getAttribute('title')) ||
                  norm(a.innerText) ||
                  norm(image ? image.alt : '');

                if (!cardText && !title) continue;

                seen.add(key);
                out.push({
                  href: key,
                  title,
                  card_text: cardText,
                });
              }

              return out;
            }
            """
        )

    @staticmethod
    def _price_values(text: str) -> list[float]:
        values: list[float] = []
        for raw in re.findall(
            r"\$\s*([0-9][0-9,]*(?:\.[0-9]{1,2})?)",
            text or "",
        ):
            try:
                values.append(float(raw.replace(",", "")))
            except ValueError:
                continue
        return values

    @classmethod
    def _row_from_dom_card(
        cls,
        card: dict,
        category: Category,
        location: Location,
    ) -> dict | None:
        url = clean_text(card.get("href"))
        title = clean_text(card.get("title"))
        card_text = clean_text(card.get("card_text"))
        if not url or not title:
            return None

        sku_match = re.search(r"-([0-9]+)\/p\/?$", url)
        if not sku_match:
            return None
        sku = sku_match.group(1)

        prices = cls._price_values(card_text)
        current = min(prices) if prices else None
        regular = max(prices) if len(prices) > 1 else current

        normalized = (card_text or "").casefold()
        unavailable_markers = (
            "agotado",
            "sin existencia",
            "no disponible",
        )
        if any(marker in normalized for marker in unavailable_markers):
            availability_status = UNAVAILABLE
            is_available = 0
            availability_raw = "dom_card_unavailable_marker"
        elif current is not None:
            availability_status = AVAILABLE
            is_available = 1
            availability_raw = "dom_card_rendered_with_price"
        else:
            availability_status = UNKNOWN
            is_available = None
            availability_raw = "dom_card_availability_unknown"

        promotion = ""
        if (
            current is not None
            and regular is not None
            and current < regular
        ):
            promotion = "Precio promocional"

        return {
            "scrape_timestamp": datetime.now()
            .astimezone()
            .isoformat(timespec="seconds"),
            "retailer": "HEB",
            "city": location.city,
            "state": location.state,
            "postal_code": location.postal_code,
            "store": location.store,
            "store_id": location.store_id,
            "department": category.department,
            "category": category.name,
            "subcategory": category.subcategory,
            "sub_subcategory": category.sub_subcategory,
            "category_id": category.id,
            "sku": sku,
            "brand": None,
            "product": title,
            "price_current": current,
            "price_regular": regular,
            "promotion": promotion,
            "availability_status": availability_status,
            "is_available": is_available,
            "availability_raw": availability_raw,
            "pickup_available": (
                None
                if is_available is None
                else bool(is_available)
            ),
            "store_context_verified": False,
            "store_context_method": "heb_dom_category_session_context",
            "url": url,
            "price_raw": card_text,
        }

    @classmethod
    def _rows_from_dom(
        cls,
        page,
        category: Category,
        location: Location,
    ) -> list[dict]:
        try:
            cards = cls._dom_product_cards(page)
        except Exception:
            return []

        rows_by_key: dict[str, dict] = {}
        for card in cards:
            row = cls._row_from_dom_card(
                card,
                category,
                location,
            )
            if row is None:
                continue
            key = clean_text(row.get("sku")) or clean_text(row.get("url"))
            if key:
                rows_by_key[key] = row
        return list(rows_by_key.values())

    @staticmethod
    def _merge_rows(
        structured_rows: list[dict],
        dom_rows: list[dict],
    ) -> list[dict]:
        merged: dict[str, dict] = {}

        for row in dom_rows:
            key = clean_text(row.get("sku")) or clean_text(row.get("url"))
            if key:
                merged[key] = dict(row)

        for row in structured_rows:
            key = clean_text(row.get("sku")) or clean_text(row.get("url"))
            if not key:
                continue
            existing = merged.get(key, {})
            combined = dict(existing)
            for field, value in row.items():
                if value is not None and value != "":
                    combined[field] = value
            merged[key] = combined

        return list(merged.values())

    @staticmethod
    def _accept_cookies(page) -> None:
        for label in (
            "Aceptar todo",
            "Aceptar",
            "Entendido",
        ):
            try:
                button = page.get_by_role(
                    "button",
                    name=re.compile(label, re.I),
                )
                if button.count() and button.first.is_visible():
                    button.first.click(timeout=2_000)
                    page.wait_for_timeout(400)
                    return
            except Exception:
                continue

    def _click_show_more(self, page) -> bool:
        for selector in self.SHOW_MORE_SELECTORS:
            try:
                node = page.locator(selector).first
                if node.count() == 0 or not node.is_visible():
                    continue
                if not node.is_enabled():
                    continue
                node.scroll_into_view_if_needed(timeout=3_000)
                node.click(timeout=5_000)
                return True
            except Exception:
                continue
        return False

    @staticmethod
    def _same_category_page(current_url: str, expected_url: str) -> bool:
        current = urlsplit(current_url or "")
        expected = urlsplit(expected_url or "")
        return bool(
            current.netloc.casefold() == expected.netloc.casefold()
            and current.path.rstrip("/").casefold()
            == expected.path.rstrip("/").casefold()
        )

    @staticmethod
    def _click_numeric_page(page, page_number: int) -> bool:
        """Click a visible numeric paginator control such as 2, 3, 4."""
        try:
            candidates = page.locator("a, button").filter(
                has_text=re.compile(
                    rf"^\\s*{page_number}\\s*$"
                )
            )
        except Exception:
            return False

        for index in range(candidates.count()):
            try:
                node = candidates.nth(index)
                if not node.is_visible():
                    continue

                # Require pagination-like context: the nearby container
                # must expose at least two visible numeric controls.
                numeric_siblings = node.evaluate(
                    r"""
                    el => {
                      let parent = el.parentElement;
                      for (let depth = 0; depth < 5 && parent; depth++) {
                        const controls = Array.from(
                          parent.querySelectorAll('a,button')
                        ).filter(item => {
                          const text = (item.innerText || '').trim();
                          const visible = !!(
                            item.offsetWidth ||
                            item.offsetHeight ||
                            item.getClientRects().length
                          );
                          return visible && /^\d+$/.test(text);
                        });
                        if (controls.length >= 2) return controls.length;
                        parent = parent.parentElement;
                      }
                      return 0;
                    }
                    """
                )
                if int(numeric_siblings or 0) < 2:
                    continue

                node.scroll_into_view_if_needed(timeout=3_000)
                node.click(timeout=5_000)
                try:
                    page.wait_for_load_state(
                        "domcontentloaded",
                        timeout=15_000,
                    )
                except PlaywrightTimeoutError:
                    pass
                page.wait_for_timeout(1_500)
                return True
            except Exception:
                continue

        return False

    def _click_native_next_page(self, page) -> bool:
        selectors = (
            'a[rel="next"]',
            'button[aria-label*="Siguiente" i]',
            'a[aria-label*="Siguiente" i]',
            'button[title*="Siguiente" i]',
            'a[title*="Siguiente" i]',
            'button:has-text("Siguiente")',
            'a:has-text("Siguiente")',
            'button:has-text("Next")',
            'a:has-text("Next")',
        )

        for selector in selectors:
            try:
                node = page.locator(selector).first
                if node.count() == 0 or not node.is_visible():
                    continue
                if node.evaluate(
                    """el => (
                      el.disabled === true ||
                      el.getAttribute('aria-disabled') === 'true'
                    )"""
                ):
                    continue
                node.scroll_into_view_if_needed(timeout=3_000)
                before = page.url
                node.click(timeout=5_000)
                try:
                    page.wait_for_load_state(
                        "domcontentloaded",
                        timeout=20_000,
                    )
                except PlaywrightTimeoutError:
                    pass
                page.wait_for_timeout(1_500)
                return page.url != before or True
            except Exception:
                continue

        # Fallback: inspect same-category links carrying a page query and
        # click the lowest page number greater than the current page.
        try:
            candidates = page.locator(
                'a[href*="/cuidado-personal-y-belleza/higiene-dental"][href*="page="]'
            ).evaluate_all(
                r"""
                els => els.map(el => {
                  try {
                    const url = new URL(el.href, location.href);
                    const pageNo = Number(url.searchParams.get('page'));
                    return {
                      href: url.href,
                      page: Number.isFinite(pageNo) ? pageNo : null,
                      text: (el.innerText || '').trim(),
                      visible: !!(
                        el.offsetWidth ||
                        el.offsetHeight ||
                        el.getClientRects().length
                      )
                    };
                  } catch (_) {
                    return null;
                  }
                }).filter(Boolean)
                """
            )
        except Exception:
            candidates = []

        current_page = 1
        try:
            current_parts = urlsplit(page.url)
            current_query = dict(
                parse_qsl(
                    current_parts.query,
                    keep_blank_values=True,
                )
            )
            current_page = int(current_query.get("page") or 1)
        except Exception:
            current_page = 1

        valid = [
            item
            for item in candidates
            if item.get("visible")
            and isinstance(item.get("page"), (int, float))
            and int(item["page"]) > current_page
        ]
        if not valid:
            return False

        next_page = min(int(item["page"]) for item in valid)
        try:
            node = page.locator(
                f'a[href*="page={next_page}"]'
            ).first
            if node.count() == 0 or not node.is_visible():
                return False
            node.scroll_into_view_if_needed(timeout=3_000)
            node.click(timeout=5_000)
            try:
                page.wait_for_load_state(
                    "domcontentloaded",
                    timeout=20_000,
                )
            except PlaywrightTimeoutError:
                pass
            page.wait_for_timeout(1_500)
            return True
        except Exception:
            return False

    def _scroll_for_more_products(self, page) -> bool:
        try:
            before = len(self._dom_product_cards(page))
        except Exception:
            before = 0

        try:
            page.evaluate(
                """
                () => window.scrollTo(
                  0,
                  document.documentElement.scrollHeight
                )
                """
            )
            page.wait_for_timeout(1_500)
        except Exception:
            return False

        try:
            after = len(self._dom_product_cards(page))
        except Exception:
            after = before
        return after > before

    def scrape_category_on_page(
        self,
        page,
        category: Category,
        location: Location,
    ) -> list[dict]:
        """Scrape HEB using an existing browser page/session."""
        self.run_meta = {
            "retailer": "HEB",
            "category_id": category.id,
            "category_url": category.url,
            "blocked_detected": False,
            "structured_transport": "productSearchV3",
            "browser_session": "existing_cdp_manual_page",
            "initial_navigation": "manual_heb_page_same_tab_navigation",
        }
        self._payloads = []
        self._response_errors = []
        self._response_urls = []

        try:
            page.on("response", self._capture_product_search_response)
        except Exception:
            pass

        if not self._same_category_page(
            page.url,
            category.url,
        ):
            # Igual que Soriana manual: el usuario abre HEB y el scraper
            # navega dentro de ESA MISMA pestaña/sesión.
            page.evaluate(
                "(url) => window.location.assign(url)",
                category.url,
            )
            try:
                page.wait_for_load_state(
                    "domcontentloaded",
                    timeout=45_000,
                )
            except PlaywrightTimeoutError:
                pass
            page.wait_for_timeout(2_500)

        page.wait_for_timeout(self.wait_ms)
        self._assert_not_blocked(page)
        self._accept_cookies(page)
        page.wait_for_timeout(1_200)

        target = self._target_from_body(page)
        dom_rows_by_key: dict[str, dict] = {}
        pagination_pages: list[dict] = []

        first_page_rows = self._rows_from_dom(
            page,
            category,
            location,
        )
        for row in first_page_rows:
            key = (
                clean_text(row.get("sku"))
                or clean_text(row.get("url"))
            )
            if key:
                dom_rows_by_key[key] = row

        pagination_pages.append(
            {
                "step": 0,
                "method": "initial_dom",
                "url": page.url,
                "rows_on_page": len(first_page_rows),
                "cumulative_rows": len(dom_rows_by_key),
                "target_products": target,
            }
        )

        clicks = 0
        numeric_page_clicks = 0
        native_next_clicks = 0
        scroll_rounds = 0
        no_growth_rounds = 0
        step = 0

        first_page_size = max(len(first_page_rows), 1)
        expected_pages = (
            (target + first_page_size - 1) // first_page_size
            if target is not None and target > 0
            else 1
        )

        # HEB currently renders a numeric paginator (1, 2, 3, 4...).
        # Prefer those native controls because they preserve the user's
        # existing Chrome session and match the visible storefront.
        for page_number in range(2, expected_pages + 1):
            if (
                target is not None
                and target > 0
                and len(dom_rows_by_key) >= target
            ):
                break

            if not self._click_numeric_page(page, page_number):
                break

            numeric_page_clicks += 1
            step += 1
            self._assert_not_blocked(page)

            body_target = self._target_from_body(page)
            if body_target is not None and body_target > 0:
                target = max(target or 0, body_target)

            current_rows = self._rows_from_dom(
                page,
                category,
                location,
            )
            before = len(dom_rows_by_key)
            for row in current_rows:
                key = (
                    clean_text(row.get("sku"))
                    or clean_text(row.get("url"))
                )
                if key:
                    dom_rows_by_key[key] = row
            after = len(dom_rows_by_key)

            pagination_pages.append(
                {
                    "step": step,
                    "method": "numeric_page",
                    "page_number": page_number,
                    "url": page.url,
                    "rows_on_page": len(current_rows),
                    "new_rows": after - before,
                    "cumulative_rows": after,
                    "target_products": target,
                }
            )

            if after == before:
                no_growth_rounds += 1
            else:
                no_growth_rounds = 0

            if no_growth_rounds >= 2:
                break

        # Generic storefront fallbacks are retained only if the numeric
        # paginator did not cover the catalogue.
        while (
            step < self.max_show_more_clicks
            and (
                target is None
                or target <= 0
                or len(dom_rows_by_key) < target
            )
        ):
            method = None
            if self._click_show_more(page):
                clicks += 1
                method = "show_more"
            elif self._click_native_next_page(page):
                native_next_clicks += 1
                method = "native_next"
            elif self._scroll_for_more_products(page):
                scroll_rounds += 1
                method = "scroll_lazy_load"
            else:
                break

            step += 1
            page.wait_for_timeout(1_200)
            self._assert_not_blocked(page)

            body_target = self._target_from_body(page)
            if body_target is not None and body_target > 0:
                target = max(target or 0, body_target)

            current_rows = self._rows_from_dom(
                page,
                category,
                location,
            )
            before = len(dom_rows_by_key)
            for row in current_rows:
                key = (
                    clean_text(row.get("sku"))
                    or clean_text(row.get("url"))
                )
                if key:
                    dom_rows_by_key[key] = row
            after = len(dom_rows_by_key)

            pagination_pages.append(
                {
                    "step": step,
                    "method": method,
                    "url": page.url,
                    "rows_on_page": len(current_rows),
                    "new_rows": after - before,
                    "cumulative_rows": after,
                    "target_products": target,
                }
            )

            if after == before:
                no_growth_rounds += 1
            else:
                no_growth_rounds = 0

            if no_growth_rounds >= 2:
                break

        structured_rows, structured_target = self._rows_from_payloads(
            self._payloads,
            category,
            location,
        )
        dom_rows = list(dom_rows_by_key.values())
        rows = self._merge_rows(
            structured_rows,
            dom_rows,
        )
        target_candidates = [
            value
            for value in (target, structured_target)
            if value is not None and int(value) > 0
        ]
        target = max(target_candidates) if target_candidates else None

        products = len(rows)
        sku_complete = sum(
            bool(clean_text(row.get("sku")))
            for row in rows
        )
        price_complete = sum(
            row.get("price_current") is not None
            for row in rows
        )
        url_complete = sum(
            bool(clean_text(row.get("url")))
            for row in rows
        )
        availability_complete = sum(
            row.get("is_available") in (0, 1)
            for row in rows
        )
        price_order_errors = sum(
            row.get("price_current") is not None
            and row.get("price_regular") is not None
            and float(row["price_current"])
            > float(row["price_regular"])
            for row in rows
        )

        coverage = (
            products / target
            if target is not None and target > 0
            else 0.0
        )

        status_name = "SUCCESS"
        if products <= 0:
            status_name = "EMPTY"
        elif (
            target is None
            or target <= 0
            or coverage < 0.90
            or (sku_complete / products) < 0.90
            or (price_complete / products) < 0.90
            or (url_complete / products) < 0.90
            or (availability_complete / products) < 0.90
            or (
                (products - price_order_errors)
                / products
            )
            < 0.90
        ):
            status_name = "PARTIAL"

        self.run_meta.update(
            {
                "status": status_name,
                "target_products": target,
                "products": products,
                "coverage": coverage,
                "sku_complete": sku_complete,
                "price_complete": price_complete,
                "url_complete": url_complete,
                "availability_complete": availability_complete,
                "price_order_errors": price_order_errors,
                "structured_responses": len(self._payloads),
                "dom_rows": len(dom_rows),
                "pagination_method": (
                    "numeric_page"
                    if numeric_page_clicks > 0
                    else (
                        "show_more"
                        if clicks > 0
                        else (
                            "native_next"
                            if native_next_clicks > 0
                            else (
                                "scroll_lazy_load"
                                if scroll_rounds > 0
                                else "initial_dom"
                            )
                        )
                    )
                ),
                "pages_visited": len(pagination_pages),
                "pagination_pages": pagination_pages,
                "catalogue_source": (
                    "productSearchV3+dom_fallback"
                    if self._payloads and dom_rows
                    else (
                        "productSearchV3"
                        if self._payloads
                        else "dom_fallback"
                    )
                ),
                "show_more_clicks": clicks,
                "numeric_page_clicks": numeric_page_clicks,
                "native_next_clicks": native_next_clicks,
                "scroll_rounds": scroll_rounds,
                "response_errors": len(self._response_errors),
                "final_url": page.url,
            }
        )
        self._save_diagnostics(page, category.id)
        return rows

    def scrape_category(
        self,
        category: Category,
        location: Location,
    ) -> list[dict]:
        """Legacy isolated-browser mode retained for diagnostics only."""
        with sync_playwright() as p:
            launch_kwargs = {"headless": self.headless}
            if self.browser_channel:
                launch_kwargs["channel"] = self.browser_channel

            browser = p.chromium.launch(**launch_kwargs)
            context = browser.new_context(
                locale="es-MX",
                viewport={"width": 1440, "height": 1000},
            )
            page = context.new_page()
            try:
                rows = self.scrape_category_on_page(
                    page,
                    category,
                    location,
                )
                self.run_meta["browser_session"] = "isolated_playwright"
                return rows
            except PlaywrightTimeoutError as exc:
                self.run_meta["status"] = "NETWORK_UNAVAILABLE"
                self.run_meta["error"] = f"TimeoutError: {exc}"
                self._save_diagnostics(page, f"{category.id}_timeout")
                raise HEBNetworkUnavailable(str(exc)) from exc
            finally:
                context.close()
                browser.close()


